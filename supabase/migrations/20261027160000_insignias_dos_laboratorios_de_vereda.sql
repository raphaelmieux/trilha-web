/*
  Uma insígnia por laboratório de vereda — as duzentas e dezenove das vinte e
  seis veredas abertas.

  A regra é "todo laboratório concluído rende uma conquista", e até aqui a
  vereda rendia uma só, no fim. Quem venceu sete dos doze laboratórios de uma
  vereda não tinha nada na estante dizendo isso. O critério nasce do currículo
  (`insigniasDosLaboratoriosDeVereda`), e esta migration semeia as linhas —
  sem a linha, a insígnia é ignorada em silêncio.

  ── De onde sai cada coluna ───────────────────────────────────────────────
  O código sai do id da vereda e do id da lição, que nunca mudam. O nome é o
  título do laboratório, a descrição diz de qual vereda ele é, o ícone é o do
  laboratório e a classe fica um patamar abaixo da classe da vereda — a mesma
  régua que põe o laboratório de trilha abaixo da trilha. As linhas foram
  geradas do próprio catálogo, e `insignias.test.ts` e `estante.test.ts`
  comparam tupla a tupla.

  ── Quem já venceu recebe agora, com a data de quando venceu ──────────────
  `evaluateBadges` concederia na próxima atividade de cada um, mas com a data
  de hoje e o contexto da ação que a disparou — o cartão diria que a pessoa
  venceu ontem um laboratório do mês passado, e quem voltasse depois de
  percorrer três veredas receberia trinta avisos de uma vez. A segunda parte
  concede a partir dos eventos `vereda_laboratorio` que já estão gravados,
  com a data do primeiro de cada laboratório. O id da vereda também é lido do
  campo antigo `trilha`, de quando ela se chamava mini-trilha: uma decisão
  nossa não se cobra de quem já andou.
*/

